package dev.liftonway.core.designsystem.animation

import android.content.Context
import androidx.annotation.RawRes
import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.rememberUpdatedState
import androidx.compose.ui.Modifier
import com.airbnb.lottie.LottieCompositionFactory
import com.airbnb.lottie.RenderMode
import com.airbnb.lottie.compose.LottieAnimation
import com.airbnb.lottie.compose.LottieClipSpec
import com.airbnb.lottie.compose.LottieCompositionSpec
import com.airbnb.lottie.compose.LottieConstants
import com.airbnb.lottie.compose.rememberLottieAnimatable
import com.airbnb.lottie.compose.rememberLottieComposition
import dev.liftonway.core.designsystem.R

/**
 * The app's animations (generated by android/tools/lottie/generate.py).
 * @param introEnd progress where a play-once intro ends and the loop begins; 0 loops the whole file.
 * @param loops false plays once and holds the last frame.
 */
enum class LiftAnimation(@param:RawRes val res: Int, val introEnd: Float = 0f, val loops: Boolean = true) {
    SplashLogo(R.raw.splash_logo, loops = false),
    TravelCar(R.raw.travel_car),
    FindRide(R.raw.find_ride),
    PostRide(R.raw.post_ride),
    Success(R.raw.success_check, loops = false),
    EmptyBox(R.raw.empty_box),
    NoRides(R.raw.no_rides, introEnd = 30f / 150f),
    Searching(R.raw.searching),
    WalletCoins(R.raw.wallet_coins),
    Bell(R.raw.bell),
    RouteMap(R.raw.route_map),
    LoadingDots(R.raw.loading_dots),
    ;

    companion object {
        /** Parses every file once at start-up so no screen waits on JSON parsing on its first frame. */
        fun preload(context: Context) = entries.forEach { LottieCompositionFactory.fromRawRes(context, it.res) }
    }
}

@Composable
fun LiftLottie(
    animation: LiftAnimation,
    modifier: Modifier = Modifier,
    playing: Boolean = true,
    speed: Float = 1f,
    onFinished: () -> Unit = {},
) {
    val composition by rememberLottieComposition(LottieCompositionSpec.RawRes(animation.res))
    val animatable = rememberLottieAnimatable()
    val finished by rememberUpdatedState(onFinished)

    LaunchedEffect(composition, playing) {
        val comp = composition ?: return@LaunchedEffect
        if (!playing) return@LaunchedEffect
        if (animation.introEnd > 0f && animatable.progress < animation.introEnd) {
            animatable.animate(comp, clipSpec = LottieClipSpec.Progress(0f, animation.introEnd), speed = speed, continueFromPreviousAnimate = true)
        }
        if (animation.loops) {
            animatable.animate(
                comp,
                clipSpec = LottieClipSpec.Progress(animation.introEnd, 1f),
                iterations = LottieConstants.IterateForever,
                speed = speed,
            )
        } else {
            animatable.animate(comp, speed = speed, continueFromPreviousAnimate = true)
            finished()
        }
    }

    LottieAnimation(
        composition = composition,
        progress = { animatable.progress },
        modifier = modifier,
        // Lottie picks hardware rendering where the device and the animation's features allow it.
        renderMode = RenderMode.AUTOMATIC,
    )
}
